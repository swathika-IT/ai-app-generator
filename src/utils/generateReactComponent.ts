/**
 * Generates a self-contained React + Tailwind TSX component from a config array.
 * Output can be pasted into any React project with Tailwind CSS.
 */
export function generateReactComponent(
  config: unknown[],
  componentName = "GeneratedComponent",
): string {
  const configStr = JSON.stringify(config, null, 2);
  const now = new Date().toISOString().slice(0, 10);

  const lines: string[] = [
    `// Generated by AppForge on ${now}`,
    `// Paste into any React + Tailwind CSS project.`,
    `// Requires: react, tailwindcss`,
    ``,
    `import React from "react";`,
    ``,
    `// ── Config ────────────────────────────────────────────────────────────────`,
    `// eslint-disable-next-line @typescript-eslint/no-explicit-any`,
    `const CONFIG: any[] = ${configStr};`,
    ``,
    `// ── Renderer ──────────────────────────────────────────────────────────────`,
    `// eslint-disable-next-line @typescript-eslint/no-explicit-any`,
    `function renderItem(item: any, key?: React.Key): React.ReactNode {`,
    `  switch (item.type) {`,
    `    // ── heading ─────────────────────────────────────────────────────────`,
    `    case "heading": {`,
    `      const Tag = ("h" + (item.level ?? 2)) as keyof React.JSX.IntrinsicElements;`,
    `      const sizes: Record<number, string> = {`,
    `        1: "text-4xl", 2: "text-2xl", 3: "text-xl", 4: "text-lg",`,
    `      };`,
    `      return (`,
    `        <Tag key={key} className={"font-bold " + (sizes[item.level ?? 2] ?? "text-xl")}>`,
    `          {item.text}`,
    `        </Tag>`,
    `      );`,
    `    }`,
    ``,
    `    // ── input ───────────────────────────────────────────────────────────`,
    `    case "input":`,
    `      return (`,
    `        <div key={key} className="flex flex-col gap-1.5">`,
    `          {item.label && (`,
    `            <label className="text-sm font-medium">{item.label}</label>`,
    `          )}`,
    `          <input`,
    `            type={item.inputType ?? "text"}`,
    `            placeholder={item.placeholder}`,
    `            className="border rounded-md px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500"`,
    `          />`,
    `        </div>`,
    `      );`,
    ``,
    `    // ── textarea ─────────────────────────────────────────────────────────`,
    `    case "textarea":`,
    `      return (`,
    `        <div key={key} className="flex flex-col gap-1.5">`,
    `          {item.label && (`,
    `            <label className="text-sm font-medium">{item.label}</label>`,
    `          )}`,
    `          <textarea`,
    `            rows={item.rows ?? 4}`,
    `            placeholder={item.placeholder}`,
    `            className="border rounded-md px-3 py-2 text-sm resize-y focus:outline-none focus:ring-2 focus:ring-blue-500"`,
    `          />`,
    `        </div>`,
    `      );`,
    ``,
    `    // ── select ───────────────────────────────────────────────────────────`,
    `    case "select":`,
    `      return (`,
    `        <div key={key} className="flex flex-col gap-1.5">`,
    `          {item.label && (`,
    `            <label className="text-sm font-medium">{item.label}</label>`,
    `          )}`,
    `          <select className="border rounded-md px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500 bg-white">`,
    `            {(item.options ?? []).map((opt: any) => (`,
    `              <option key={opt.value} value={opt.value}>{opt.label}</option>`,
    `            ))}`,
    `          </select>`,
    `        </div>`,
    `      );`,
    ``,
    `    // ── button ───────────────────────────────────────────────────────────`,
    `    case "button": {`,
    `      const variantCls: Record<string, string> = {`,
    `        primary:   "bg-blue-600 text-white hover:bg-blue-700",`,
    `        secondary: "bg-gray-200 text-gray-800 hover:bg-gray-300",`,
    `        danger:    "bg-red-600  text-white hover:bg-red-700",`,
    `      };`,
    `      const cls = variantCls[item.variant ?? "primary"] ?? variantCls.primary;`,
    `      return (`,
    `        <button`,
    `          key={key}`,
    `          type={item.isSubmit ? "submit" : "button"}`,
    `          className={"px-4 py-2 rounded-md text-sm font-medium transition-colors " + cls}`,
    `        >`,
    `          {item.text}`,
    `        </button>`,
    `      );`,
    `    }`,
    ``,
    `    // ── card ─────────────────────────────────────────────────────────────`,
    `    case "card":`,
    `      return (`,
    `        <div key={key} className="border rounded-xl p-5 bg-white shadow-sm">`,
    `          <p className="text-sm font-medium text-gray-500">{item.title}</p>`,
    `          <p className="text-2xl font-bold mt-1">{String(item.value)}</p>`,
    `          {item.description && (`,
    `            <p className="text-xs text-gray-500 mt-1">{item.description}</p>`,
    `          )}`,
    `          {item.trend != null && (`,
    `            <p className={"text-xs mt-1 " + (item.trend >= 0 ? "text-green-600" : "text-red-600")}>`,
    `              {item.trend >= 0 ? "+" : ""}{item.trend}%`,
    `            </p>`,
    `          )}`,
    `        </div>`,
    `      );`,
    ``,
    `    // ── table ────────────────────────────────────────────────────────────`,
    `    case "table":`,
    `      return (`,
    `        <div key={key} className="overflow-x-auto rounded-lg border">`,
    `          {item.label && (`,
    `            <p className="px-4 py-2 font-medium text-sm border-b bg-gray-50">{item.label}</p>`,
    `          )}`,
    `          <table className="w-full text-sm">`,
    `            <thead className="bg-gray-50">`,
    `              <tr>`,
    `                {(item.columns ?? []).map((col: any) => (`,
    `                  <th key={col.key} className="px-4 py-2 text-left font-medium text-gray-600">`,
    `                    {col.label}`,
    `                  </th>`,
    `                ))}`,
    `              </tr>`,
    `            </thead>`,
    `            <tbody>`,
    `              {(item.rows ?? []).map((row: any, i: number) => (`,
    `                <tr key={i} className="border-t hover:bg-gray-50">`,
    `                  {(item.columns ?? []).map((col: any) => (`,
    `                    <td key={col.key} className="px-4 py-2">{row[col.key]}</td>`,
    `                  ))}`,
    `                </tr>`,
    `              ))}`,
    `            </tbody>`,
    `          </table>`,
    `        </div>`,
    `      );`,
    ``,
    `    // ── section ──────────────────────────────────────────────────────────`,
    `    case "section":`,
    `      return (`,
    `        <div key={key} className="border rounded-xl p-5 space-y-4">`,
    `          {item.title && (`,
    `            <h3 className="font-semibold text-lg">{item.title}</h3>`,
    `          )}`,
    `          {(item.children ?? []).map((child: any) => renderItem(child, child.id))}`,
    `        </div>`,
    `      );`,
    ``,
    `    default:`,
    `      return null;`,
    `  }`,
    `}`,
    ``,
    `// ── Component ─────────────────────────────────────────────────────────────`,
    `export function ${componentName}() {`,
    `  return (`,
    `    <div className="space-y-4 p-4">`,
    `      {CONFIG.map((item: any) => renderItem(item, item.id))}`,
    `    </div>`,
    `  );`,
    `}`,
  ];

  return lines.join("\n");
}
